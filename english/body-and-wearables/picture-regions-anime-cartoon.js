  function segment(start, end, radius) {
    var dx = end[0] - start[0], dy = end[1] - start[1];
    return [(start[0] + end[0]) / 2, (start[1] + end[1]) / 2,
      Math.sqrt(dx * dx + dy * dy) / 2 + radius / 3, radius,
      Math.atan2(dy, dx) * 180 / Math.PI];
  }

